-- Tenant column shapes real apps use, and places tables live. Every name is schema-qualified:
-- the test connections run with search_path = tenancy, public; Flyway's own session may not.
-- No index on the tenant column (except where it leads a primary key): seq scans are the worst case.

CREATE TABLE public.t_int (
    id        serial  PRIMARY KEY,
    tenant_id integer NOT NULL,
    amount    numeric NOT NULL
);

CREATE TABLE public.t_bigint (
    id        bigserial PRIMARY KEY,
    tenant_id bigint    NOT NULL,
    amount    numeric   NOT NULL
);

-- uuid primary key too: min(uuid) does not exist, so id lookups must ORDER BY ... LIMIT 1.
CREATE TABLE public.t_uuid (
    id        uuid    PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid    NOT NULL,
    amount    numeric NOT NULL
);

CREATE TABLE public.t_text (
    id        bigserial PRIMARY KEY,
    tenant_id text      NOT NULL,
    amount    numeric   NOT NULL
);

-- Same idea under another column name; only observed when tenantColumn = "company_id".
CREATE TABLE public.t_company (
    id         bigserial PRIMARY KEY,
    company_id bigint    NOT NULL,
    amount     numeric   NOT NULL
);

-- The tenant column leads a composite primary key, so a filtered read can use the index.
CREATE TABLE public.t_composite (
    tenant_id integer NOT NULL,
    id        integer GENERATED BY DEFAULT AS IDENTITY,
    amount    numeric NOT NULL,
    PRIMARY KEY (tenant_id, id)
);

-- Quoted identifiers: mixed case, and a reserved word that is lower-case but still needs quoting.
CREATE TABLE public."MixedCase" (
    id        bigserial PRIMARY KEY,
    tenant_id text      NOT NULL,
    amount    numeric   NOT NULL
);

CREATE TABLE public."order" (
    id        bigserial PRIMARY KEY,
    tenant_id text      NOT NULL,
    amount    numeric   NOT NULL
);

-- Outside the identifier allowlist on purpose: must be skipped with a reason, never built into SQL.
CREATE TABLE public."odd name" (
    tenant_id text NOT NULL
);

-- Non-public schema first on the search_path, with a same-named table in public that it shadows.
CREATE SCHEMA IF NOT EXISTS tenancy;

CREATE TABLE tenancy.t_in_schema (
    id        serial  PRIMARY KEY,
    tenant_id integer NOT NULL,
    amount    numeric NOT NULL
);

CREATE TABLE public.t_in_schema (
    id        serial  PRIMARY KEY,
    tenant_id integer NOT NULL,
    amount    numeric NOT NULL
);

-- A schema that is not on the search_path: only observed when named explicitly.
CREATE SCHEMA IF NOT EXISTS archive;

CREATE TABLE archive.t_archived (
    id        serial  PRIMARY KEY,
    tenant_id integer NOT NULL,
    amount    numeric NOT NULL
);
